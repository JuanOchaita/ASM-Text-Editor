parser = argparse.ArgumentParser()
parser.add_argument("imagen")
args = parser.parse_args()

paleta = [
    (
        tuple(int(codigo[i:i + 2], 16) for i in (0, 2, 4)),
        numero
    )
    for codigo, numero in colors_8086.items()
]

sustitutos = {}


def convertir_color(rgb):
    codigo = "".join(f"{canal:02X}" for canal in rgb)

    if codigo in colors_8086:
        return colors_8086[codigo]

    if rgb not in sustitutos:
        sustitutos[rgb] = min(
            paleta,
            key=lambda item: sum(
                (canal - referencia) ** 2
                for canal, referencia in zip(rgb, item[0])
            )
        )[1]

    return sustitutos[rgb]


with Image.open(args.imagen).convert("RGB") as imagen:
    for y in range(imagen.height):
        numeros = []

        for x in range(imagen.width):
            rgb = imagen.getpixel((x, y))
            numeros.append(str(convertir_color(rgb)))

        print(f"db {','.join(numeros)}")