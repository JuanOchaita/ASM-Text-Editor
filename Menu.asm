AddFileLine PROC
    push ax
    push bx
    push cx
    push dx
    push si
    push di

    ; Construir el nombre del archivo: texto ingresado + ".HTM" + 0
    mov si,offset newfiletext
    mov di,offset newfilename
    mov cx,newfiletextlen
    cmp cx,0
    je addfile_copydone

addfile_copyloop:
    mov al,[si]
    mov [di],al
    inc si
    inc di
    dec cx
    jnz addfile_copyloop

addfile_copydone:
    mov BYTE PTR [di],'.'
    inc di
    mov BYTE PTR [di],'H'
    inc di
    mov BYTE PTR [di],'T'
    inc di
    mov BYTE PTR [di],'M'
    inc di
    mov BYTE PTR [di],0

    ; Crear el archivo nuevo (vacío)
    mov ah,3Ch
    xor cx,cx
    mov dx,offset newfilename
    int 21h
    jc addfile_done

    mov filehandle,ax
    mov bx,filehandle
    mov ah,3Eh
    int 21h

addfile_done:
    pop di
    pop si
    pop dx
    pop cx
    pop bx
    pop ax
    ret
AddFileLine ENDP

